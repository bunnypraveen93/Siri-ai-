     */
    fun correctTranscription(text: String): String {
        var correctedText = text
        
        for ((wrongWord, correctWord) in correctionMap) {
            // ఆ తప్పు పదం టెక్స్ట్ లో ఉంటే సరైన పదంతో మారుస్తుంది
            correctedText = correctedText.replace(wrongWord, correctWord, ignoreCase = true)
        }
        
        return correctedText.trim()
    }
